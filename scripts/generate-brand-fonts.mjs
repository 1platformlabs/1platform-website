#!/usr/bin/env node
/**
 * Regenerates `src/lib/brand-fonts.generated.ts` from `public/fonts/`.
 *
 * The derived brand assets (favicon, touch icon, social card) draw the mark as
 * glyph OUTLINES, so they need the font bytes at request time. They are
 * embedded instead of read from disk because the served tree and the test tree
 * put `public/` in different places, and a path that only resolves in one of
 * them is a mark that silently falls back to a system face in the other.
 *
 * `tests/tenant-brand-glyphs.spec.ts` fails when this file drifts from the
 * fonts the page itself loads.
 */
import { readFileSync, writeFileSync } from 'node:fs'

export const BRAND_FONT_FILES = {
  'space-grotesk': 'public/fonts/space-grotesk-latin-700-normal.woff2',
  'instrument-serif': 'public/fonts/instrument-serif-latin-400-normal.woff2',
}

const entries = Object.entries(BRAND_FONT_FILES).map(([key, path]) => {
  const base64 = readFileSync(path).toString('base64')
  return `  // ${path}\n  '${key}': '${base64}',`
})

writeFileSync(
  'src/lib/brand-fonts.generated.ts',
  `// GENERATED by scripts/generate-brand-fonts.mjs — do not edit by hand.\n` +
    `export const BRAND_FONT_FILES = ${JSON.stringify(BRAND_FONT_FILES, null, 2)} as const\n\n` +
    `export const BRAND_FONT_BASE64: Record<keyof typeof BRAND_FONT_FILES, string> = {\n${entries.join('\n')}\n}\n`,
)
